def test_large_still_keeps_original_pixels_and_raw_256_is_not_assumed_aligned(tmp_path, monkeypatch):
    original = np.random.default_rng(42).integers(0, 256, (900, 2200, 3), dtype=np.uint8)
    source = tmp_path / "large.png"
    cv2.imwrite(str(source), cv2.cvtColor(original, cv2.COLOR_RGB2BGR))
    assert prepare_detection_media(source, "image", tmp_path) == source
    media = FaceMedia(tmp_path)
    seen = []

    class Aligner:
        def align_with_region(self, rgb, size):
            seen.append(rgb)
            return rgb[:256, :256], {}

    media._aligner = Aligner()
    media.extract(source, "image")
    assert np.array_equal(seen[0], original)
    small = tmp_path / "ordinary-256.png"
    cv2.imwrite(str(small), np.zeros((256, 256, 3), dtype=np.uint8))
    media.extract(small, "image")
    assert len(seen) == 2  # Dimensions alone do not establish face alignment.


def test_256_still_is_always_sent_through_face_alignment(tmp_path):
    rgb = np.random.default_rng(7).integers(0, 256, (256, 256, 3), dtype=np.uint8)
    path = tmp_path / "already-cropped.png"
    cv2.imwrite(str(path), cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR))
    media = FaceMedia(tmp_path)
    seen = []
    expected = np.full((256, 256, 3), 77, dtype=np.uint8)
    class Aligner:
        def align_with_region(self, image, size):
            seen.append(image.copy())
            assert size == 256
            return expected, {"x": 0, "y": 0, "width": 1, "height": 1}
    media._aligner = Aligner()
    samples, count, _ = media.extract(path, "image")
    assert count == 1 and len(seen) == 1
    assert np.array_equal(seen[0], rgb)
    assert np.array_equal(samples[0].image, expected)


def test_original_video_sampling_matches_decoded_pixels_without_resize(tmp_path, monkeypatch):
    source = tmp_path / "source.mkv"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i",
                    "testsrc2=s=1200x700:r=10:d=4", "-c:v", "ffv1", str(source)], check=True)
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    assert prepare_detection_media(source, "video", tmp_path) == source
    indices = uniform_frame_indices(40)
    reference = {}
    cap = cv2.VideoCapture(str(source))
    for index in range(40):
        ok, bgr = cap.read()
        assert ok
        if index in indices:
            reference[index] = hashlib.sha256(cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB).tobytes()).hexdigest()
    cap.release()
    seen = []
    media = FaceMedia(tmp_path)

    def face(rgb, index, timestamp):
        assert rgb.shape == (700, 1200, 3)  # No historical 1024-pixel cap.
        assert hashlib.sha256(rgb.tobytes()).hexdigest() == reference[index]
        seen.append(index)
        return None if index == indices[3] else FaceSample(rgb[:256, :256], index, timestamp, {})

    monkeypatch.setattr(media, "_face", face)
    samples, count, duration = media.extract(source, "video")
    assert seen == indices and count == 32 and len(samples) == 31
    assert duration == 4 and samples[-1].timestamp == 3.9
    assert hashlib.sha256(source.read_bytes()).hexdigest() == digest


def test_256_video_always_aligns_each_sample_without_duplicating_frames(tmp_path):
    source = tmp_path / "already-cropped.mkv"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i",
                    "testsrc2=s=256x256:r=5:d=0.6", "-c:v", "ffv1", str(source)], check=True)
    media = FaceMedia(tmp_path)
    seen = []
    class Aligner:
        def align_with_region(self, image, size):
            seen.append(image.copy())
            assert size == 256
            return np.full((size, size, 3), 77, dtype=np.uint8), {}
    media._aligner = Aligner()
    samples, count, _ = media.extract(source, "video")
    assert count == 3 and [s.index for s in samples] == [0, 1, 2]
    assert len(seen) == 3
    assert all(np.all(sample.image == 77) for sample in samples)
    cap = cv2.VideoCapture(str(source))
    for image in seen:
        ok, bgr = cap.read()
        assert ok and np.array_equal(image, cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB))
    cap.release()


def test_alignment_pixels_match_official_deepfakebench_reference():
    # Expected digest generated by executing the unmodified nested img_align_crop
    # from DeepfakeBench commit 525b2f333af6854e276809303290944fa163744e.
    rgb = np.random.default_rng(123).integers(0, 256, (480, 640, 3), dtype=np.uint8)
    landmarks = np.array([[220, 165], [350, 172], [288, 238], [236, 300], [335, 305]])
    crop = _align_crop(rgb, landmarks, 256)
    assert crop.shape == (256, 256, 3)
    assert hashlib.sha256(crop.tobytes()).hexdigest() == "e11a7377866e38e189d53fbf6e7fd40c9cadf6365f22d51290f8d3d6597f7c5e"


@pytest.mark.parametrize("legacy_mode", [None, "aligned"])
def test_client_cannot_skip_face_alignment(client, monkeypatch, legacy_mode):
    from conftest import fake_get_detector
    login(client)
    upload = client.post("/api/v1/uploads", files={"file": ("face.png", PNG_BYTES, "image/png")}).json()
    seen = []
    def factory(media, spec, *args):
        seen.append(spec.preprocessing_version)
        assert len(args) == 5  # No input mode is passed to the detector.
        return fake_get_detector(media, spec)
    monkeypatch.setattr("app.tasks.analysis.get_detector", factory)
    payload = {"upload_id": upload["id"]}
    if legacy_mode is not None:
        payload["input_face_mode"] = legacy_mode
    response = client.post("/api/v1/analyses", json=payload)
    assert response.status_code == 201
    analysis = response.json()
    assert analysis["input_face_mode"] == "raw"
    assert analysis["detector_runs"][0]["preprocessing_version"] == "dfb-face256-clip224-v3"
    run_analysis(analysis["id"])
    assert seen == ["dfb-face256-clip224-v3"]
    report = client.get(f"/api/v1/analyses/{analysis['id']}").json()
    assert report["status"] == "completed" and report["input_face_mode"] == "raw"
    assert client.get("/api/v1/analyses").json()[0]["input_face_mode"] == "raw"


def test_input_mode_migration_does_not_relabel_legacy_reports(tmp_path):
    database = tmp_path / "legacy.db"
    environment = {**os.environ, "DATABASE_URL": f"sqlite:///{database}"}
    root = Path(__file__).resolve().parents[1]
    def migrate(target):
        subprocess.run([sys.executable, "-m", "alembic", "upgrade", target], cwd=root, env=environment, check=True, capture_output=True)
    migrate("20261020_0003")
    with sqlite3.connect(database) as db:
        db.execute("INSERT INTO analyses (id,upload_id,user_id,status,progress,cancel_requested,created_at) VALUES (?,?,?,'completed',100,0,CURRENT_TIMESTAMP)", [uuid.uuid4().hex for _ in range(3)])
    migrate("head")
    with sqlite3.connect(database) as db:
        assert db.execute("SELECT status,input_face_mode FROM analyses").fetchone() == ("completed", None)
